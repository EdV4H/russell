/**
 * 前回いつまで動いていたか（#124）。
 *
 * 積み残しの確認は既定で直近12時間しか見ない。窓を切っているのは「起動のたびに何日も前の
 * スレッドへ返信し始める」のを防ぐためで、そこは正しい。**ただし前提が崩れる**——
 * その理屈は「基本的に動いている」が前提だが、実際には長時間止まることがある。
 *
 * 「古い話を掘り返さない」と「**留守にしていた分に応える**」は別のことなのに、
 * 同じ窓で切っていた。実際、4日間止まっていた間に来た呼びかけは一件も拾われなかった。
 *
 * > [!IMPORTANT]
 * > **`agent.stopped` は当てにできない。** 正常終了でしか残らず、強制終了や電源断では
 * > 残らない——そして困るのはたいてい後者である。代わりに使うのは**死活の記録**（#78）で、
 * > 動いている間ずっと打ち続けているので、どんな落ち方をしても最後の一打が残る。
 */
export interface PresenceCapability {
  /**
   * **前回の稼働がいつまで続いていたか。** 初めての起動なら `undefined`。
   *
   * > [!IMPORTANT]
   * > **今回の分で上書きする前に読むこと。** 死活の記録は1行を上書きしていく形なので、
   * > 起動して打ってから読むと、読めるのは「たった今」になる（前回が消える）。
   */
  lastSeenAt(): Date | undefined;
}

/** services のキー。 */
export const PRESENCE_SERVICE = "presence";
